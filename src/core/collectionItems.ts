const ach = (achievement: string) => ({ achievement });
const word = (kind: 'front' | 'back', id: string, star: Star, name: string, source: Item['source'] = 'gacha'): Item =>
  ({ id: `${kind === 'front' ? 'f' : 'b'}-${id}`, kind, star, source, name });
const plate = (id: string, star: Star, name: string, bg: string, border: string, text: string,
  pattern: NonNullable<Item['plate']>['pattern'] = 'plain', source: Item['source'] = 'gacha'): Item =>
  ({ id: `p-${id}`, kind: 'plate', star, source, name, plate: { bg, border, text, pattern } });
const sound = (id: string, star: Star, name: string, s: NonNullable<Item['sound']>, source: Item['source'] = 'gacha'): Item =>
  ({ id: `k-${id}`, kind: 'sound', star, source, name, sound: s });
const sticker = (series: string, slot: number, id: string, star: Star, name: string, source: Item['source'] = 'gacha'): Item =>
  ({ id: `st-${id}`, kind: 'sticker', star, source, name, sticker: { series, slot } });

